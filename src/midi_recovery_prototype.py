"""EMULATION ONLY: bounded per-port deferred MIDI Off/Stop in Thumb-2.

Not imported by seq_Patch/build_phase1_patches; no firmware patch hunks here.
The harness supplies a832-byte RAM arena and replaces only emulated port
vtables and checked emulator-only router overlays. Production heap reservation,
initialization/lifetime, all producer
entry points and hardware/IRQ scheduling are NOT proven by this prototype.

After a known failure/reentrant send, the modeled3-byte send path stays
quarantined: new On/Clock/Start/Continue/CC sends are rejected. Deferred Off
(release vel0) and Stop are accepted. Bulk SysEx admission is bounded and
quarantined; pending reports borrowed payload ownership even when disconnected.
The experimental router rejects busy/nested submissions before copying its
shared payload. Callers must handle failure/retry; production does not use this.
No automatic resume
or CC broadcast. Healthy3-byte sends keep their native path and bytes.
"""
from thumb_asm import (
    Asm, add_sp_imm, adds_imm8, adds_reg, ands_reg, b, b_cond_w, bics_reg,
    b_w, bl, blx_reg, bx_lr, cmp_imm, cmp_reg, ldr_imm, ldr_sp, ldrb_imm,
    ldrh_imm, lsls_imm, lsls_reg, lsrs_imm, mov_reg, movs_imm, movt, movw,
    orrs_reg, pop, push, raw, str_imm, str_sp, strb_imm, strh_imm,
    sub_sp_imm, subs_imm8, tst_reg,
)

CODE_BASE = 0x08070000
STATE_BASE = 0x20047000  # TEST ARENA ONLY: below real heap current; NOT free production RAM
MAGIC = 0x3150524D  # MRP1
HEADER_SIZE = 16
PORTS = 3
ENTRY_SIZE = 0x110
STATE_SIZE = HEADER_SIZE + PORTS*ENTRY_SIZE  #832B incl768B bitmap
FLAGS, BUSY, CURSOR, COUNT, SEEN, BITMAP = 4, 5, 6, 8, 10, 16
FAULT, STOP_PENDING = 1, 2
WORD_BUDGET = 8  # max8 bitmap-word inspections /Off attempts per port poll
NATIVE_SEND, NATIVE_POLL, NATIVE_COUNT = 0x080401FE, 0x080402B4, 0x0802A37E
NATIVE_SYSEX, NATIVE_PENDING, NATIVE_ROUTER = 0x08040232, 0x0804028C, 0x080298B8
ROUTER, ROUTER_BUSY = 4, 8  # header, one registered boot-lifetime router
# Emulator overlays only. Never returned as production PatchHunks.
ROUTER_PROLOGUE = bytes.fromhex('2de9f047')
ROUTER_WAIT = 0x08029962
ROUTER_WAIT_BYTES = bytes.fromhex('49465046')
ROUTER_FAILURE = 0x08029930


def arm_code(base=CODE_BASE, state=STATE_BASE):
    if (base % 4 or state % 4 or not 0x0806A570 <= base < 0x08080000
            or not 0x20000000 <= state < state+STATE_SIZE <= 0x2004F660):
        raise ValueError('Prototype code/test arena outside aligned application/SRAM bounds')
    a = Asm(base)
    E = a.emit

    def imm(rd, value):
        E(movw, rd, value & 0xFFFF)
        E(movt, rd, value >> 16)

    def bc(label, condition):
        E(b_cond_w, label, condition)

    def mask(rd):
        E(raw, bytes([0xEF, 0xF3, 0x10, 0x80 | rd]))  # MRS rd,PRIMASK
        E(raw, bytes.fromhex('72b6'))  # CPSID i

    def restore(rn):
        E(raw, bytes([0x80 | rn, 0xF3, 0x10, 0x88]))  # MSR PRIMASK,rn

    # Lookup never dereferences the caller's port pointer or writes RAM.
    a.label('rp_lookup')
    E(movs_imm, 1, 3)
    E(tst_reg, 0, 1)
    bc('lookup_none', 'ne')
    imm(1, 0x20000000)
    E(cmp_reg, 0, 1)
    bc('lookup_none', 'lo')
    imm(1, 0x2004F648)  # complete24B object below the production state block
    E(cmp_reg, 0, 1)
    bc('lookup_none', 'hi')
    imm(3, state)
    E(ldr_imm, 1, 3)
    imm(2, MAGIC)
    E(cmp_reg, 1, 2)
    bc('lookup_none', 'ne')
    E(cmp_imm, 0, 0)
    bc('lookup_none', 'eq')
    for n in range(PORTS):
        imm(3, state+HEADER_SIZE+n*ENTRY_SIZE)
        E(ldr_imm, 1, 3)
        E(cmp_reg, 0, 1)
        bc('lookup_found', 'eq')
    a.label('lookup_none')
    E(movs_imm, 0, 0)
    E(bx_lr)
    a.label('lookup_found')
    E(mov_reg, 0, 3)
    E(bx_lr)

    # Acquire only with caller PRIMASK0. Nested send/poll will not touch FIFO.
    a.label('rp_begin')
    mask(1)
    E(cmp_imm, 1, 0)
    bc('begin_busy', 'ne')
    E(ldrb_imm, 2, 0, BUSY)
    E(cmp_imm, 2, 0)
    bc('begin_busy', 'ne')
    E(movs_imm, 2, 1)
    E(strb_imm, 2, 0, BUSY)
    E(movs_imm, 0, 1)
    E(b, 'begin_end')
    a.label('begin_busy')
    E(movs_imm, 0, 0)
    a.label('begin_end')
    restore(1)
    E(bx_lr)

    a.label('rp_end')
    mask(1)
    E(movs_imm, 2, 0)
    E(strb_imm, 2, 0, BUSY)
    restore(1)
    E(bx_lr)

    a.label('rp_fault')
    mask(1)
    E(ldrb_imm, 2, 0, FLAGS)
    E(movs_imm, 3, FAULT | STOP_PENDING)
    E(orrs_reg, 2, 3)
    E(strb_imm, 2, 0, FLAGS)
    restore(1)
    E(bx_lr)

    # r0=entry,r1=3-byte message. Atomically record closing obligations.
    a.label('rp_defer')
    E(push, [3, 4, 5, 6, 7], lr=True)  #24B
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(ldrb_imm, 0, 5)
    E(cmp_imm, 0, 0xFC)
    bc('defer_stop', 'eq')
    E(mov_reg, 1, 0)
    E(movs_imm, 2, 0xF0)
    E(ands_reg, 1, 2)
    E(cmp_imm, 1, 0x80)
    bc('defer_off', 'eq')
    E(cmp_imm, 1, 0x90)
    bc('defer_reject', 'ne')
    E(ldrb_imm, 1, 5, 2)
    E(cmp_imm, 1, 0)
    bc('defer_reject', 'ne')
    a.label('defer_off')
    E(ldrb_imm, 1, 5, 1)
    E(cmp_imm, 1, 127)
    bc('defer_reject', 'hi')
    E(movs_imm, 2, 15)
    E(ands_reg, 0, 2)
    E(lsls_imm, 0, 0, 7)
    E(adds_reg, 6, 0, 1)  # key0..2047
    E(lsrs_imm, 0, 6, 5)
    E(lsls_imm, 0, 0, 2)
    E(adds_reg, 5, 4, 0)
    E(adds_imm8, 5, BITMAP)
    E(movs_imm, 0, 31)
    E(ands_reg, 6, 0)
    E(movs_imm, 7, 1)
    E(lsls_reg, 7, 6)
    mask(3)
    E(ldr_imm, 1, 5)
    E(tst_reg, 1, 7)
    bc('defer_already', 'ne')
    E(ldrh_imm, 0, 4, COUNT)
    E(movw, 2, 2048)
    E(cmp_reg, 0, 2)
    bc('defer_bad_count', 'hs')
    E(orrs_reg, 1, 7)
    E(str_imm, 1, 5)
    E(adds_imm8, 0, 1)
    E(strh_imm, 0, 4, COUNT)
    a.label('defer_already')
    E(ldrb_imm, 1, 4, FLAGS)
    E(movs_imm, 2, FAULT | STOP_PENDING)
    E(orrs_reg, 1, 2)
    E(strb_imm, 1, 4, FLAGS)
    restore(3)
    E(movs_imm, 0, 1)
    E(b, 'defer_return')
    a.label('defer_bad_count')
    restore(3)
    E(b, 'defer_reject')
    a.label('defer_stop')
    E(mov_reg, 0, 4)
    E(bl, 'rp_fault')
    E(movs_imm, 0, 1)
    E(b, 'defer_return')
    a.label('defer_reject')
    E(ldrb_imm, 0, 4, FLAGS)
    E(movs_imm, 1, FAULT)
    E(tst_reg, 0, 1)
    bc('defer_zero', 'ne')
    E(mov_reg, 0, 4)
    E(bl, 'rp_fault')
    a.label('defer_zero')
    E(movs_imm, 0, 0)
    a.label('defer_return')
    E(pop, [3, 4, 5, 6, 7], pc=True)

    a.label('rp_ready')
    E(push, [4], lr=True)
    E(ldr_imm, 0, 0, 0x14)
    E(ldr_imm, 1, 0)
    E(ldr_imm, 2, 1, 0x0C)
    E(blx_reg, 2)
    E(pop, [4], pc=True)

    # Raw ownership, unlike4028C: do not hide a borrowed pointer when ready=0.
    # A damaged cursor>total also stays busy. No driver calls or poll loop.
    a.label('rp_sysex_remaining')
    E(ldr_imm, 0, 0, 0x10)
    E(ldr_imm, 1, 0)  # aligned atomic pair: cursor16,total16
    E(lsrs_imm, 2, 1, 16)
    E(lsls_imm, 1, 1, 16)
    E(lsrs_imm, 1, 1, 16)
    E(movs_imm, 0, 0)
    E(cmp_reg, 1, 2)
    bc('sysex_remaining_return', 'eq')
    E(movs_imm, 0, 1)
    a.label('sysex_remaining_return')
    E(bx_lr)

    a.label('rp_sysex_pending')
    E(push, [4], lr=True)
    E(mov_reg, 4, 0)
    E(bl, 'rp_lookup')
    E(cmp_imm, 0, 0)
    bc('sysex_pending_busy', 'eq')
    E(ldrb_imm, 1, 0, BUSY)
    E(cmp_imm, 1, 0)
    bc('sysex_pending_busy', 'ne')
    E(mov_reg, 0, 4)
    E(bl, 'rp_sysex_remaining')
    E(pop, [4], pc=True)
    a.label('sysex_pending_busy')
    E(movs_imm, 0, 1)
    E(pop, [4], pc=True)

    # Port result:1=borrowed descriptor payload,0=rejected; descriptor itself
    # may die on return. At most one native service pass, never40232's wait.
    a.label('rp_sysex_send')
    E(push, [3, 4, 5, 6, 7], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(bl, 'rp_lookup')
    E(cmp_imm, 0, 0)
    bc('sysex_return', 'eq')
    E(mov_reg, 6, 0)
    E(bl, 'rp_begin')
    E(cmp_imm, 0, 0)
    bc('sysex_return', 'eq')
    E(movs_imm, 7, 0)
    E(ldrb_imm, 0, 6, FLAGS)
    E(cmp_imm, 0, 0)
    bc('sysex_release', 'ne')
    E(mov_reg, 0, 4)
    E(bl, 'rp_ready')
    E(cmp_imm, 0, 0)
    bc('sysex_release', 'eq')
    E(mov_reg, 0, 4)
    E(bl, 'rp_sysex_remaining')
    E(cmp_imm, 0, 0)
    bc('sysex_bind', 'eq')
    E(mov_reg, 0, 4)
    E(bl, NATIVE_POLL)
    E(mov_reg, 0, 4)
    E(bl, 'rp_sysex_remaining')
    E(cmp_imm, 0, 0)
    bc('sysex_release', 'ne')
    a.label('sysex_bind')
    # Length fits the native16-bit counters. Native caller validates F0/F7.
    E(ldr_imm, 1, 5, 4)
    E(cmp_imm, 1, 2)
    bc('sysex_release', 'lo')
    E(lsrs_imm, 0, 1, 16)
    E(cmp_imm, 0, 0)
    bc('sysex_release', 'ne')
    E(ldr_imm, 0, 5)
    E(ldr_imm, 2, 4, 0x10)
    # Recheck fault atomically after native driver callbacks/nested calls.
    mask(3)
    E(ldrb_imm, 5, 6, FLAGS)
    E(cmp_imm, 5, 0)
    bc('sysex_unlock', 'ne')
    a.label('sysex_commit')
    E(str_imm, 0, 4, 8)
    E(str_imm, 1, 4, 12)
    E(movs_imm, 0, 0)
    E(strh_imm, 0, 2)
    E(strh_imm, 1, 2, 2)
    E(movs_imm, 7, 1)
    E(strb_imm, 7, 6, SEEN)
    a.label('sysex_unlock')
    restore(3)
    a.label('sysex_release')
    E(mov_reg, 0, 6)
    E(bl, 'rp_end')
    E(mov_reg, 0, 7)
    a.label('sysex_return')
    E(pop, [3, 4, 5, 6, 7], pc=True)

    # Router result is inverted:0=all selected ports accepted,1=failure.
    # Serialize its shared buffer across validation/copy/port fanout/callback.
    # Native pending wait is separately overlaid to return failure BEFORE copy.
    a.label('rp_sysex_route')
    E(push, [4, 5, 6, 7], lr=True)
    E(sub_sp_imm, 4)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(mov_reg, 6, 2)
    imm(7, state)
    E(ldr_imm, 0, 7)
    imm(1, MAGIC)
    E(cmp_reg, 0, 1)
    bc('route_reject', 'ne')
    E(ldr_imm, 0, 7, ROUTER)
    E(cmp_imm, 0, 0)
    bc('route_reject', 'eq')
    E(cmp_reg, 0, 4)
    bc('route_reject', 'ne')
    mask(3)
    E(cmp_imm, 3, 0)
    bc('route_busy', 'ne')
    E(ldrb_imm, 0, 7, ROUTER_BUSY)
    E(cmp_imm, 0, 0)
    bc('route_busy', 'ne')
    E(movs_imm, 0, 1)
    E(strb_imm, 0, 7, ROUTER_BUSY)
    restore(3)
    # Bounds before native F0/F7 validation (which reads length-1).
    E(ldr_imm, 2, 6, 4)
    E(cmp_imm, 2, 2)
    bc('route_bad_length', 'lo')
    E(lsrs_imm, 1, 2, 16)
    E(cmp_imm, 1, 0)
    bc('route_bad_length', 'ne')
    # Standard buffer=360B; alternate buffer capacity lives in router+8 span.
    E(mov_reg, 0, 4)
    E(adds_imm8, 0, 0x24)
    E(ldrb_imm, 0, 0)
    E(cmp_imm, 0, 0)
    bc('route_extended', 'ne')
    E(movw, 1, 360)
    E(b, 'route_capacity')
    a.label('route_extended')
    E(ldr_imm, 0, 4, 8)
    E(ldr_imm, 1, 0, 4)
    a.label('route_capacity')
    E(cmp_reg, 2, 1)
    bc('route_bad_length', 'hi')
    E(mov_reg, 0, 4)
    E(mov_reg, 1, 5)
    E(mov_reg, 2, 6)
    E(bl, 'native_router_trampoline')
    E(b, 'route_release')
    a.label('route_bad_length')
    E(movs_imm, 0, 1)
    a.label('route_release')
    mask(3)
    E(movs_imm, 1, 0)
    E(strb_imm, 1, 7, ROUTER_BUSY)
    restore(3)
    E(b, 'route_return')
    a.label('route_busy')
    restore(3)
    a.label('route_reject')
    E(movs_imm, 0, 1)
    a.label('route_return')
    E(add_sp_imm, 4)
    E(pop, [4, 5, 6, 7], pc=True)

    a.label('rp_send')
    E(push, [3, 4, 5, 6, 7], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(bl, 'rp_lookup')
    E(cmp_imm, 0, 0)
    bc('send_return', 'eq')
    E(mov_reg, 6, 0)
    E(bl, 'rp_begin')
    E(mov_reg, 7, 0)
    E(cmp_imm, 7, 0)
    bc('send_defer', 'eq')
    E(ldrb_imm, 0, 6, FLAGS)
    E(movs_imm, 1, FAULT)
    E(tst_reg, 0, 1)
    bc('send_defer', 'ne')
    E(mov_reg, 0, 4)
    E(mov_reg, 1, 5)
    E(bl, NATIVE_SEND)
    E(cmp_imm, 0, 0)
    bc('send_failed', 'eq')
    E(movs_imm, 1, 1)
    E(strb_imm, 1, 6, SEEN)
    E(b, 'send_release')
    a.label('send_failed')
    # Never-ready ports with no accepted messages have no closing obligation.
    E(ldrb_imm, 1, 6, SEEN)
    E(cmp_imm, 1, 0)
    bc('send_release', 'eq')
    a.label('send_defer')
    E(mov_reg, 0, 6)
    E(mov_reg, 1, 5)
    E(bl, 'rp_defer')
    a.label('send_release')
    E(mov_reg, 5, 0)
    E(cmp_imm, 7, 0)
    bc('send_result', 'eq')
    E(mov_reg, 0, 6)
    E(bl, 'rp_end')
    a.label('send_result')
    E(mov_reg, 0, 5)
    a.label('send_return')
    E(pop, [3, 4, 5, 6, 7], pc=True)

    # service stack: packet[0..3], selected word pointer+4, bit mask+8,
    # last native worker result+12. Frame40B, BL aligned8 throughout.
    a.label('rp_poll')
    E(push, [3, 4, 5, 6, 7], lr=True)
    E(sub_sp_imm, 16)
    E(mov_reg, 5, 0)
    E(bl, 'rp_lookup')
    E(cmp_imm, 0, 0)
    bc('poll_return', 'eq')
    E(mov_reg, 4, 0)
    E(bl, 'rp_begin')
    E(cmp_imm, 0, 0)
    bc('poll_return', 'eq')
    E(movs_imm, 0, 0)
    E(str_sp, 0, 12)
    E(mov_reg, 0, 5)
    E(bl, 'rp_ready')
    E(cmp_imm, 0, 0)
    bc('poll_ready', 'ne')
    E(ldrb_imm, 0, 4, SEEN)
    E(cmp_imm, 0, 0)
    bc('poll_result', 'eq')
    E(mov_reg, 0, 4)
    E(bl, 'rp_fault')
    E(b, 'poll_result')  # retain FIFO; do not call401CA queue-clear
    a.label('poll_ready')
    E(mov_reg, 0, 5)
    E(bl, NATIVE_POLL)
    E(str_sp, 0, 12)
    E(ldrb_imm, 0, 4, FLAGS)
    E(movs_imm, 1, FAULT)
    E(tst_reg, 0, 1)
    bc('poll_result', 'eq')
    E(ldrb_imm, 6, 4, CURSOR)
    E(movs_imm, 0, 63)
    E(ands_reg, 6, 0)
    E(movs_imm, 7, WORD_BUDGET)
    a.label('poll_scan')
    E(ldrh_imm, 0, 4, COUNT)
    E(cmp_imm, 0, 0)
    bc('poll_stop', 'eq')
    E(movw, 1, 2048)
    E(cmp_reg, 0, 1)
    bc('poll_save_cursor', 'hi')  # damaged metadata, fail closed
    E(lsls_imm, 0, 6, 2)
    E(adds_reg, 1, 4, 0)
    E(adds_imm8, 1, BITMAP)
    E(str_sp, 1, 4)
    E(ldr_imm, 2, 1)
    E(cmp_imm, 2, 0)
    bc('poll_next_word', 'eq')
    E(raw, bytes.fromhex('92faa2f2 b2fa82f2'))  # RBIT r2,r2; CLZ r2,r2
    E(movs_imm, 0, 1)
    E(lsls_reg, 0, 2)
    E(str_sp, 0, 8)
    E(lsls_imm, 1, 6, 5)
    E(adds_reg, 1, 1, 2)  # channel/note key
    E(movs_imm, 0, 127)
    E(ands_reg, 0, 1)
    E(mov_reg, 3, 13)
    E(strb_imm, 0, 3, 1)
    E(lsrs_imm, 1, 1, 7)
    E(movs_imm, 0, 0x80)
    E(orrs_reg, 1, 0)
    E(strb_imm, 1, 3)
    E(movs_imm, 0, 0)
    E(strb_imm, 0, 3, 2)
    E(strb_imm, 0, 3, 3)
    E(mov_reg, 0, 5)
    E(mov_reg, 1, 13)
    E(bl, NATIVE_SEND)
    E(cmp_imm, 0, 0)
    bc('poll_save_cursor', 'eq')  # no bit/count clear without acceptance
    # Coalescing a repeated same-key Off during enqueue is safe because this
    # port cannot accept ANY new On after FAULT. Other-key bits survive.
    mask(3)
    E(ldr_sp, 1, 4)
    E(ldr_imm, 0, 1)
    E(ldr_sp, 2, 8)
    E(bics_reg, 0, 2)
    E(str_imm, 0, 1)
    E(ldrh_imm, 0, 4, COUNT)
    E(subs_imm8, 0, 1)
    E(strh_imm, 0, 4, COUNT)
    restore(3)
    E(b, 'poll_budget')
    a.label('poll_next_word')
    E(adds_imm8, 6, 1)
    E(movs_imm, 0, 63)
    E(ands_reg, 6, 0)
    a.label('poll_budget')
    E(subs_imm8, 7, 1)
    bc('poll_scan', 'ne')
    E(b, 'poll_save_cursor')
    a.label('poll_stop')
    E(ldrb_imm, 0, 4, FLAGS)
    E(movs_imm, 1, STOP_PENDING)
    E(tst_reg, 0, 1)
    bc('poll_save_cursor', 'eq')
    E(movs_imm, 0, 0xFC)
    E(str_sp, 0)
    E(mov_reg, 0, 5)
    E(mov_reg, 1, 13)
    E(bl, NATIVE_SEND)
    E(cmp_imm, 0, 0)
    bc('poll_save_cursor', 'eq')
    mask(3)
    E(ldrh_imm, 0, 4, COUNT)
    E(cmp_imm, 0, 0)
    bc('poll_keep_stop', 'ne')  # nested new Off -> final Stop still required
    E(ldrb_imm, 0, 4, FLAGS)
    E(movs_imm, 1, STOP_PENDING)
    E(bics_reg, 0, 1)
    E(strb_imm, 0, 4, FLAGS)
    a.label('poll_keep_stop')
    restore(3)
    a.label('poll_save_cursor')
    E(strb_imm, 6, 4, CURSOR)
    a.label('poll_result')
    E(ldr_imm, 0, 5, 4)
    E(bl, NATIVE_COUNT)
    E(ldrh_imm, 1, 4, COUNT)
    E(orrs_reg, 0, 1)
    E(ldrb_imm, 1, 4, FLAGS)
    E(movs_imm, 2, STOP_PENDING)
    E(ands_reg, 1, 2)
    E(orrs_reg, 0, 1)
    E(ldr_sp, 1, 12)
    E(orrs_reg, 0, 1)
    E(mov_reg, 6, 0)
    E(mov_reg, 0, 4)
    E(bl, 'rp_end')
    E(movs_imm, 0, 0)
    E(cmp_imm, 6, 0)
    bc('poll_return', 'eq')
    E(movs_imm, 0, 1)
    a.label('poll_return')
    E(add_sp_imm, 16)
    E(pop, [3, 4, 5, 6, 7], pc=True)
    a.label('native_router_trampoline')
    E(raw, ROUTER_PROLOGUE)
    E(b_w, NATIVE_ROUTER+4)
    code, labels = a.assemble()
    if base+len(code) > 0x08080000:
        raise ValueError('Prototype code exceeds application flash bounds')
    return code, labels
